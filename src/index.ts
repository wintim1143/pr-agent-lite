#!/usr/bin/env node
/**
 * 进程入口 —— **自检模式**。
 *
 * ## 为什么单独有一个入口
 *
 * 交付形态是「一个常驻服务 + 一个可随时问它一句的检查命令」。二者共用同一段自检代码
 * （`startup.ts`），但目的不同：
 *
 * - 本入口（`npm start`）：**只做自检就退出**。部署后第一件事就是跑它 ——
 *   在没有任何请求的情况下确认「这台机器上，本次实际生效的端点与模型是什么」。
 *   这条信息在服务正常时看不出价值，出事时是第一个要看的。
 * - 服务入口（`npm run mcp`）：同样先跑自检，然后开始对外提供能力。
 *
 * 把自检做成**独立可跑**的，就等于把「配置期事实」变成一条可断言的事实 ——
 * 不必等到第一次业务调用才间接发现配错了。
 *
 * 退出码恒为 0：自检报告的是事实，不是通过/不通过。缺配置会被标成 warn 并打印出来，
 * 但那是使用者要判断的事（缺的可能是本次根本用不到的通道）。
 */
import { logStartupSelfCheck } from './startup.js';

logStartupSelfCheck();
